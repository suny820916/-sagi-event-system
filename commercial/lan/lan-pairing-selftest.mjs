import assert from 'node:assert/strict';
import { LanPairing } from './lan-pairing.mjs';
let clock = 1_000;
const pairing = new LanPairing({ now: () => clock, ttlMs: 10_000, sessionTtlMs: 60_000, maxAttempts: 3 });
assert.throws(() => pairing.issue(), /LOCAL_APPROVAL_REQUIRED/);
const issued = pairing.issue({ localOperatorApproved: true });
assert.match(issued.code, /^\d{6}$/);
assert.throws(() => pairing.redeem('abcdef'), /PAIRING_INVALID/);
assert.throws(() => pairing.redeem('123'), /PAIRING_INVALID/);
assert.throws(() => pairing.redeem('wrong'), /PAIRING_INVALID/);
assert.throws(() => pairing.redeem(issued.code), /PAIRING_UNAVAILABLE/);
const next = pairing.issue({ localOperatorApproved: true });
const { token } = pairing.redeem(next.code);
assert.equal(pairing.verify(token), true);
assert.equal(pairing.verify(token + 'x'), false);
assert.throws(() => pairing.redeem(next.code), /PAIRING_UNAVAILABLE/);
clock += 60_000;
assert.equal(pairing.verify(token), false);
const expiring = pairing.issue({ localOperatorApproved: true });
clock += 10_000;
assert.throws(() => pairing.redeem(expiring.code), /PAIRING_UNAVAILABLE/);
const revoked = pairing.issue({ localOperatorApproved: true });
const active = pairing.redeem(revoked.code);
assert.equal(pairing.revoke(active.token), true);
assert.equal(pairing.verify(active.token), false);
console.log('lan-pairing-selftest PASS');

const bounded = new LanPairing({ now: () => clock, ttlMs: 10_000, sessionTtlMs: 60_000, maxSessions: 1 });
const first = bounded.issue({ localOperatorApproved: true });
const firstSession = bounded.redeem(first.code);
assert.equal(bounded.verify(firstSession.token), true);
const second = bounded.issue({ localOperatorApproved: true });
assert.throws(() => bounded.redeem(second.code), /SESSION_LIMIT_REACHED/);
assert.equal(bounded.verify(firstSession.token), true);
assert.equal(bounded.revoke(firstSession.token), true);
const third = bounded.issue({ localOperatorApproved: true });
const thirdSession = bounded.redeem(third.code);
assert.equal(bounded.verify(thirdSession.token), true);
clock += 60_000;
const fourth = bounded.issue({ localOperatorApproved: true });
assert.equal(bounded.verify(bounded.redeem(fourth.code).token), true);
assert.throws(() => new LanPairing({ maxSessions: 0 }), /invalid pairing policy/);
console.log('lan-pairing-bounded-sessions PASS');
